import { PGlite } from '@electric-sql/pglite';
import { readFileSync } from 'node:fs';
import { schemaText } from './schema-loader.mjs';
const HERE=new URL('.',import.meta.url).pathname;
const db=new PGlite();
await db.exec(readFileSync(HERE+'pglite-boot.sql','utf8'));
await db.exec(`create or replace function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;`);
await db.exec(schemaText(HERE+'../../database/complete-schema.sql'));
console.log('--- trigger definition as built ---');
const r=await db.query(`select pg_get_triggerdef(oid) d from pg_trigger where tgname='trg_report_scores_no_prep'`);
console.log(r.rows[0]?.d);
